import { type BriefingTool, toolBriefingLine } from './credentials/tool-words.ts';
import type { AgentStatus } from './enums.ts';
import { AGENT_INSTRUCTIONS_MAX } from './org.ts';

/**
 * An agent's place in the company, as every turn of it is told (docs/harness.md, "Standing instructions"): a short
 * block generated from the live org chart (who it is, whom it reports to, who reports to it, its teammates and the
 * chain up to the top), placed before the agent's own instructions. Pure, so the server (which sends it) and the web
 * (which shows it, and previews it on the Hire page) write the same text from the same chart. Archived agents are not
 * on the chart, so they are left out; paused ones are listed, marked paused. People show their display name only,
 * never an email; nobody's id is shown. Since S7.1b it ends with a line per tool profile the agent has (GitHub,
 * Atlassian): what it may do there and as whom (`toolBriefingLine`).
 */

/** A principal as the briefing reads the chart: the `GET /org/chart` node's fields it needs. */
export type BriefingNode =
  | {
      readonly kind: 'person';
      readonly principalId: string;
      readonly reportsTo: string | null;
      readonly title: string | null;
      readonly person: { readonly displayName: string | null };
    }
  | {
      readonly kind: 'agent';
      readonly principalId: string;
      readonly reportsTo: string | null;
      readonly title: string | null;
      readonly agent: { readonly name: string; readonly roleTitle: string; readonly status: AgentStatus };
    };

export interface BriefingInput {
  /** The company's name. */
  readonly company: string;
  /** The chart's nodes, in the chart's order. */
  readonly nodes: readonly BriefingNode[];
  /** The agent the briefing is for. */
  readonly principalId: string;
  /** Its tool profiles, GitHub's then Atlassian's (S7.1b); none when left out. */
  readonly tools?: readonly BriefingTool[];
}

/** The text, and a short hash of it that changes whenever the text does. */
export interface Briefing {
  readonly text: string;
  readonly version: string;
}

/** The briefing's heading: what it is, and that nobody edits it. */
export const BRIEFING_HEADING =
  '## Your place in the company (generated by Most Wanted from the org chart; not editable)';

/** The heading before the agent's own instructions, when it has any. */
export const INSTRUCTIONS_HEADING = '## Your instructions';

/** The most teammates or reports a line names; the rest are counted. */
export const BRIEFING_LIST_MAX = 25;

/** A name for a person who has given none: never their email. */
export const UNNAMED_PERSON = 'Unnamed person';

/** The longest briefing: the heading and five lines of at most `BRIEFING_LIST_MAX` names of 80 characters and more. */
export const BRIEFING_MAX = 20_000;

/** The longest section a turn's standing text adds after the agent's own instructions (S6a: a Lead's tools). */
export const STANDING_SECTION_MAX = 2_000;

/**
 * The longest standing text a turn carries: a briefing, the agent's instructions and the headings between them, and a
 * section after them (a Lead's tools). A runner older than the section never gets one, so the larger limit is safe.
 */
export const STANDING_INSTRUCTIONS_MAX = BRIEFING_MAX + AGENT_INSTRUCTIONS_MAX + 100 + STANDING_SECTION_MAX;

/** One line of words: runs of whitespace (a newline in a name) become one space, so a name cannot start a line. */
const words = (text: string): string => text.replace(/\s+/g, ' ').trim();

/** What a node is called: an agent's name, a person's display name. */
function nameOf(node: BriefingNode): string {
  if (node.kind === 'agent') return words(node.agent.name) || 'Unnamed agent';
  return words(node.person.displayName ?? '') || UNNAMED_PERSON;
}

/**
 * Its job: the title on the chart, else an agent's role title; none for a person without a title, or when it only
 * repeats the name ("QA", "QA").
 */
function roleOf(node: BriefingNode): string | null {
  const role = words(node.title ?? '') || (node.kind === 'agent' ? words(node.agent.roleTitle) : '');
  return role === '' || role.toLowerCase() === nameOf(node).toLowerCase() ? null : role;
}

/** `Name (Role; an agent, paused)`: who someone is, in a list. */
function described(node: BriefingNode): string {
  const role = roleOf(node);
  const what = node.kind === 'person' ? 'a person' : 'an agent';
  const paused = node.kind === 'agent' && node.agent.status === 'paused' ? ', paused' : '';
  return `${nameOf(node)} (${role === null ? '' : `${role}; `}${what}${paused})`;
}

/** Names in one line, the first `BRIEFING_LIST_MAX`, then how many more. */
function listed(nodes: readonly BriefingNode[]): string {
  const shown = nodes.slice(0, BRIEFING_LIST_MAX).map(described);
  const more = nodes.length - shown.length;
  return more > 0 ? `${shown.join(', ')} and ${more} more` : shown.join(', ');
}

/** The chart looked up: each principal's first entry, and its reports in chart order. Archived agents are left out. */
function indexed(nodes: readonly BriefingNode[]) {
  const byId = new Map<string, BriefingNode>();
  for (const node of nodes) {
    const archived = node.kind === 'agent' && node.agent.status === 'archived';
    if (!archived && !byId.has(node.principalId)) byId.set(node.principalId, node);
  }
  const reportsOf = (id: string) =>
    [...byId.values()].filter((node) => node.reportsTo === id && node.principalId !== id);
  return { byId, reportsOf };
}

/** The managers above a node, nearest first; a loop in the data or a manager off the chart ends it. */
function chainAbove(byId: ReadonlyMap<string, BriefingNode>, node: BriefingNode): BriefingNode[] {
  const chain: BriefingNode[] = [];
  const seen = new Set([node.principalId]);
  for (let up = node.reportsTo; up !== null && !seen.has(up); ) {
    const manager = byId.get(up);
    if (manager === undefined) break;
    chain.push(manager);
    seen.add(up);
    up = manager.reportsTo;
  }
  return chain;
}

/** `You are …`: the first line. */
function selfLine(self: BriefingNode, company: string): string {
  const role = roleOf(self);
  return `- You are ${nameOf(self)}${role === null ? '' : `, ${role},`} at ${company}, an AI agent on its org chart.`;
}

/** The lines about whom it reports to: the manager, the chain to the top when longer, the teammates. */
function upLines(index: ReturnType<typeof indexed>, self: BriefingNode): string[] {
  const chain = chainAbove(index.byId, self);
  const manager = chain[0];
  if (manager === undefined) return ['- You report to nobody on the chart.'];
  const lines = [`- You report to ${described(manager)}.`];
  if (chain.length > 1) lines.push(`- Your chain up to the top: ${chain.map(nameOf).join(' → ')}.`);
  const peers = index.reportsOf(manager.principalId).filter((node) => node.principalId !== self.principalId);
  lines.push(
    peers.length === 0
      ? `- You have no teammates: nobody else reports to ${nameOf(manager)}.`
      : `- Your teammates (also reporting to ${nameOf(manager)}): ${listed(peers)}.`,
  );
  return lines;
}

/** 32-bit FNV-1a of the text's UTF-16 code units, as 8 hex digits: the briefing's version. */
export function briefingVersion(text: string): string {
  let hash = 0x811c9dc5;
  for (let i = 0; i < text.length; i++) hash = Math.imul(hash ^ text.charCodeAt(i), 0x01000193) >>> 0;
  return hash.toString(16).padStart(8, '0');
}

/**
 * The agent's briefing (see above): the heading, then one line each for who it is, its manager, the chain up (when the
 * manager has one of their own), its teammates, its reports and each of its tool profiles. An agent not on the chart
 * (archived) is told only that.
 */
export function agentBriefing(input: BriefingInput): Briefing {
  const company = words(input.company) || 'the company';
  const index = indexed(input.nodes);
  const self = index.byId.get(input.principalId);
  const lines =
    self === undefined
      ? [`- You are not on the org chart of ${company}.`]
      : [
          selfLine(self, company),
          ...upLines(index, self),
          reportsLine(index, self),
          ...(input.tools ?? []).map(toolBriefingLine),
        ];
  const text = [BRIEFING_HEADING, '', ...lines].join('\n').slice(0, BRIEFING_MAX);
  return { text, version: briefingVersion(text) };
}

/** Who reports to it, or that nobody does. */
function reportsLine(index: ReturnType<typeof indexed>, self: BriefingNode): string {
  const reports = index.reportsOf(self.principalId);
  return reports.length === 0 ? '- Nobody reports to you.' : `- Reporting to you: ${listed(reports)}.`;
}

/**
 * What a turn carries as standing instructions: the briefing, then the agent's own instructions under their heading
 * when it has any (blank ones are left out).
 */
export function standingInstructions(briefing: string, instructions: string): string {
  if (instructions.trim() === '') return briefing;
  return `${briefing}\n\n${INSTRUCTIONS_HEADING}\n\n${instructions}`;
}
